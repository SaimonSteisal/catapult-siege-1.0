import puppeteer from 'puppeteer';
import { createServer } from 'node:http';
import { readFileSync, existsSync } from 'node:fs';
import { resolve, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const DIST = resolve(ROOT, 'dist');
const MIME={'.html':'text/html; charset=utf-8','.js':'text/javascript','.css':'text/css'};
const server = createServer((q,r)=>{let p=q.url.split('?')[0];if(p==='/')p='/index.html';const f=resolve(DIST,'.'+p);
 if(!existsSync(f)){r.writeHead(404);r.end();return}r.writeHead(200,{'Content-Type':MIME[extname(f)]||'text/plain'});r.end(readFileSync(f))});
await new Promise(r=>server.listen(0,r));
const PORT=server.address().port;
const b = await puppeteer.launch({headless:'shell',args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-dev-shm-usage']});
const p = await b.newPage();
await p.setViewport({width:900,height:600,isMobile:false,hasTouch:true});
p.on('pageerror',e=>console.log('PAGEERROR',(e&&e.stack||String(e)).slice(0,300)));
await p.goto(`http://localhost:${PORT}/index.html`,{waitUntil:'domcontentloaded'});
await new Promise(r=>setTimeout(r,3500));
const click = async (txt)=>{ await p.evaluate((t)=>{const n=Array.from(document.querySelectorAll('button,.menu-btn')).find(x=>(x.textContent||'').includes(t)); n&&n.click();}, txt); await new Promise(r=>setTimeout(r,700)); };
await click('Полигон'); await click('В ОСАДУ');
await new Promise(r=>setTimeout(r,2200));
await p.evaluate(()=>{ const b2=Array.from(document.querySelectorAll('.tut button')).find(x=>x.textContent.includes('Пропустить')); b2&&b2.click();
  const g=window.__GAME__; g.hud.show(false); window.__S__().settings.cameraDynamic=false; g.applySettings();
  g.rig.setMode('battle',{force:true}); g.rig.azGoal=200; g.rig.polGoal=76; g.rig.distGoal=36; g.rig.targetGoal.set(0,3,26); });
const shot = async (biome, theme, name) => {
  await p.evaluate((bb)=>{ const g=window.__GAME__; g.mission.biome=bb; g.mission.seed=Math.abs(g.mission.seed*7+13)|0;
    g.mission.mod={id:'calm',wind:0.1,reward:1,supply:1}; g.startMission(g.mission);
    g.hud.show(false); window.__S__().settings.cameraDynamic=false;
    g.rig.setMode('battle',{force:true}); g.rig.azGoal=200; g.rig.polGoal=76; g.rig.distGoal=36; g.rig.targetGoal.set(0,3,26);
    if (bb) g.world.applySkyTheme('sunset'); }, biome);
  await new Promise(r=>setTimeout(r,600));
  if (theme) await p.evaluate((tt)=>window.__GAME__.world.applySkyTheme(tt), theme);
  await new Promise(r=>setTimeout(r,1400));
  await p.screenshot({path:`shots/sky-${name}.png`});
  console.log('shot', name);
};
await shot('meadow','sunset','meadow-sunset');
await shot('desert','heat','desert-heat');
await shot('autumn','dawn','autumn-dawn');
await shot('volcano','ash','volcano-ash');
await shot('winter','aurora','winter-aurora');
await shot('river','storm','river-storm');
await shot('mountain','dusk','mountain-dusk');
await b.close(); server.close(); process.exit(0);
