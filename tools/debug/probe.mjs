import puppeteer from 'puppeteer';
import { createServer } from 'node:http';
import { readFileSync, existsSync } from 'node:fs';
import { resolve, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = resolve(ROOT, 'dist');
const MIME = { '.html':'text/html; charset=utf-8', '.js':'text/javascript', '.css':'text/css' };
const server = createServer((q,r)=>{ let p=q.url.split('?')[0]; if(p==='/')p='/index.html'; const f=resolve(DIST,'.'+p);
  if(!existsSync(f)){console.log('404',p); r.writeHead(404);r.end('404');return;} r.writeHead(200,{'Content-Type':MIME[extname(f)]||'application/octet-stream'}); r.end(readFileSync(f)); });
await new Promise(r=>server.listen(8932,r));
const b = await puppeteer.launch({headless:'shell', args:['--no-sandbox','--disable-setuid-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-dev-shm-usage']});
const p = await b.newPage();
await p.setViewport({width:412,height:915,isMobile:true,hasTouch:true});
p.on('console', async m=>{ let a=''; try{a=(await Promise.all(m.args().map(x=>x.jsonValue().catch(()=>x.toString())))).join(' ')}catch(e){a=m.text()} console.log('CON['+m.type()+']', a.slice(0,900)); });
p.on('pageerror', e=>console.log('PAGEERROR:', (e && e.stack || String(e)).slice(0,2500)));
await p.goto('http://localhost:8932/index.html',{waitUntil:'networkidle2',timeout:90000});
await new Promise(r=>setTimeout(r,6000));
const r = await p.evaluate(()=>{ const g=window.__GAME__; return {screen:g&&g.ui&&g.ui.current, webgl:!!(g&&g.world), trebuchet:!!(g&&g.trebuchet), splash: !!document.querySelector('#splash'), bodyText: document.body.innerText.slice(0,500)};});
console.log('STATE', JSON.stringify(r,null,1));
await p.screenshot({path:'shots/probe.png'});
await b.close(); server.close(); process.exit(0);
