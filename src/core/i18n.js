export function t(key, vars) {
  const lang = (S().lang || 'ru') === 'en' ? 1 : 0;
  let s = DICT[key] ? DICT[key][lang] : (DICT[key] ? DICT[key][0] : key);
  if (vars) for (const k in vars) s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
  return s;
}
export function hasKey(k) { return !!DICT[k]; }
export function setLang(l) { S().lang = l; }
